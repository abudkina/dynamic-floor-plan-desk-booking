/**
 * Web Worker: агрегация статистики и фильтрация бронирований
 * (тяжёлые вычисления вынесены из основного потока).
 */

/**
 * @param {MessageEvent} event
 */
self.onmessage = (event) => {
  const { тип, полезнаяНагрузка } = event.data || {};

  try {
    if (тип === 'статистика') {
      const { бронирования, всегоСтолов } = полезнаяНагрузка;
      const занято = Object.keys(бронирования || {}).length;
      const свободно = Math.max(0, всегоСтолов - занято);
      const процент =
        всегоСтолов === 0 ? 0 : Math.round((занято / всегоСтолов) * 100);

      self.postMessage({
        тип: 'статистика',
        ок: true,
        результат: { занято, свободно, процент },
      });
      return;
    }

    if (тип === 'фильтр') {
      const { столы, фильтр, бронирования } = полезнаяНагрузка;
      const отфильтрованные =
        !фильтр || фильтр === 'all'
          ? столы
          : столы.filter((стол) => стол.type === фильтр);

      const сСтатусом = отфильтрованные.map((стол) => ({
        ...стол,
        занят: Boolean(бронирования?.[стол.id]),
      }));

      self.postMessage({
        тип: 'фильтр',
        ок: true,
        результат: сСтатусом,
      });
      return;
    }

    self.postMessage({
      тип: тип || 'неизвестно',
      ок: false,
      ошибка: 'Неизвестная команда воркера.',
    });
  } catch (error) {
    self.postMessage({
      тип: тип || 'ошибка',
      ок: false,
      ошибка: error instanceof Error ? error.message : 'Сбой воркера.',
    });
  }
};
